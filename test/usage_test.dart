import 'package:flutter_flavor_overrides/src/project.dart';
import 'package:flutter_flavor_overrides/src/usage.dart';
import 'package:test/test.dart';

import 'support/project_builder.dart';

void main() {
  late ProjectBuilder project;

  setUp(() => project = ProjectBuilder());
  tearDown(() => project.delete());

  /// The packages the resolution of [dir] uses, the project discovered from
  /// [start] (default: [dir]).
  Set<String> used(String dir, {String? start, List<String>? warnings}) =>
      usedPackages(
        Project.discover(project.path(start ?? dir)),
        project.path(dir),
        warnings: warnings,
      );

  /// A pubspec.lock in [dir] that lists [packages].
  void lock(String dir, List<String> packages) {
    project.file('$dir/pubspec.lock', '''
# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
${[
      for (final name in packages)
        '  $name:\n'
            '    dependency: transitive\n'
            '    description:\n'
            '      name: $name\n'
            '      url: "https://pub.dev"\n'
            '    source: hosted\n'
            '    version: "1.0.0"\n',
    ].join()}sdks:
  dart: ">=3.4.0 <4.0.0"
''');
  }

  group('packages mode', () {
    /// app → path: packages/feature → ffo_probe; both have a dev dependency.
    void appWithFeature() {
      project.pubspec('app', '''
name: app
dependencies:
  feature:
    path: ../packages/feature
dev_dependencies:
  app_tool: 1.0.0
''');
      project.pubspec('packages/feature', '''
name: feature
dependencies:
  ffo_probe: 1.0.0
dev_dependencies:
  feature_tool: 1.0.0
''');
    }

    test('a direct dependency', () {
      project.pubspec('app', 'name: app\ndependencies:\n  ffo_probe: 1.0.0\n');

      expect(used('app'), {'ffo_probe'});
    });

    test('through a local module, the module itself included', () {
      appWithFeature();

      expect(used('app'), containsAll(['feature', 'ffo_probe']));
    });

    test('dev dependencies of the resolving package only', () {
      appWithFeature();

      expect(used('app'), {'feature', 'ffo_probe', 'app_tool'});
      expect(
        used('packages/feature', start: 'app'),
        {'ffo_probe', 'feature_tool'},
      );
    });

    test('pubspec.lock adds what comes through other packages', () {
      appWithFeature();
      lock('app', ['ffo_probe', 'transitive_plugin']);

      expect(used('app'), contains('transitive_plugin'));
      expect(
        used('packages/feature', start: 'app'),
        isNot(contains('transitive_plugin')),
      );
    });

    test('without pubspec.lock, only the visible graph', () {
      appWithFeature();

      expect(used('app'), isNot(contains('transitive_plugin')));
    });

    test('never the resolving package itself', () {
      project.pubspec('packages/feature', '''
name: feature
dependencies:
  core:
    path: ../core
''');
      // core depends back on feature: a cycle through the resolving package.
      project.pubspec('packages/core', '''
name: core
dependencies:
  feature:
    path: ../feature
''');
      lock('packages/feature', ['core', 'feature']);

      expect(used('packages/feature'), {'core'});
    });

    test('a package linked by melos, by name', () {
      project.pubspec('.', 'name: root\ndev_dependencies:\n  melos: 6.3.3\n');
      project.file(
          'melos.yaml', 'name: root\npackages:\n  - app\n  - pkgs/*\n');
      project.pubspec('app', 'name: app\ndependencies:\n  feature: 0.0.1\n');
      project.pubspec('pkgs/feature', '''
name: feature
version: 0.0.1
dependencies:
  ffo_probe: 1.0.0
''');

      expect(used('app'), {'feature', 'ffo_probe'});
      expect(used('.', start: 'app'), {'melos'});
    });

    group('a pubspec.lock that cannot be read', () {
      for (final (name, content) in [
        ('invalid YAML', 'packages: [a\n'),
        ('not a map', '- a\n'),
        ('packages not a map', 'packages: [a]\n'),
      ]) {
        test('$name is a warning naming it, and is left out', () {
          appWithFeature();
          final path = project.file('app/pubspec.lock', content);
          final warnings = <String>[];

          expect(
            used('app', warnings: warnings),
            {'feature', 'ffo_probe', 'app_tool'},
          );
          expect(warnings, [startsWith('$path: ')]);
        });
      }
    });
  });

  group('workspace', () {
    setUp(() {
      project.pubspec('.', '''
name: root
workspace:
  - a
  - b
dev_dependencies:
  root_tool: 1.0.0
''');
      project.pubspec('a', '''
name: a
resolution: workspace
dependencies:
  a_plugin: 1.0.0
dev_dependencies:
  a_tool: 1.0.0
''');
      project.pubspec('b', '''
name: b
resolution: workspace
dependencies:
  vendor:
    path: ../vendor
''');
      project.pubspec('vendor', '''
name: vendor
dependencies:
  vendor_plugin: 1.0.0
dev_dependencies:
  vendor_tool: 1.0.0
''');
    });

    test('every member, their dev dependencies, the packages they reach', () {
      expect(used('.', start: 'a'), {
        'a',
        'b',
        'vendor',
        'a_plugin',
        'a_tool',
        'root_tool',
        'vendor_plugin',
      });
    });

    test("and the root's pubspec.lock", () {
      lock('.', ['a_plugin', 'transitive_plugin']);
      // A member never has a lock of its own; one left behind does not count.
      lock('a', ['stale_plugin']);

      expect(
        used('.'),
        allOf(contains('transitive_plugin'), isNot(contains('stale_plugin'))),
      );
    });

    test("never the root's own name", () {
      project.pubspec('a', '''
name: a
resolution: workspace
dependencies:
  root: any
''');

      expect(used('.'), isNot(contains('root')));
    });
  });
}
